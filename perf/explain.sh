#!/usr/bin/env bash
# Rebuild the list-index EXPLAIN (ANALYZE, BUFFERS) evidence.
# Uses a throwaway postgres:16-alpine. Does not touch the Compose database.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NAME="${EXPLAIN_CONTAINER:-payments-explain}"
PORT="${EXPLAIN_PORT:-5433}"
IMAGE="${POSTGRES_IMAGE:-postgres:16-alpine}"

docker rm -f "$NAME" >/dev/null 2>&1 || true
docker run -d --name "$NAME" \
  -e POSTGRES_PASSWORD=postgres \
  -e POSTGRES_DB=payments \
  -p "127.0.0.1:${PORT}:5432" \
  "$IMAGE" >/dev/null

ready=0
for _ in $(seq 1 40); do
  if docker exec "$NAME" pg_isready -U postgres -d payments >/dev/null 2>&1; then
    ready=$((ready + 1))
    if [[ "$ready" -ge 2 ]]; then
      break
    fi
  else
    ready=0
  fi
  sleep 1
done
docker exec "$NAME" pg_isready -U postgres -d payments

docker exec -i "$NAME" psql -U postgres -d payments -v ON_ERROR_STOP=1 <<'SQL'
CREATE TABLE payments (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    description VARCHAR(255),
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_payments_user_status ON payments (user_id, status);
CREATE INDEX idx_payments_created_at ON payments (created_at DESC);

INSERT INTO payments (id, user_id, amount, currency, description, status, created_at, updated_at, version)
SELECT
    gen_random_uuid(),
    CASE WHEN g % 80 = 0
         THEN '11111111-1111-1111-1111-111111111111'::uuid
         ELSE (
            substr(md5((g % 4000)::text), 1, 8) || '-' ||
            substr(md5((g % 4000)::text), 9, 4) || '-' ||
            substr(md5((g % 4000)::text), 13, 4) || '-' ||
            substr(md5((g % 4000)::text), 17, 4) || '-' ||
            substr(md5((g % 4000)::text), 21, 12)
         )::uuid
    END,
    10.00,
    'BRL',
    'explain',
    'PENDING',
    TIMESTAMPTZ '2020-01-01 00:00:00+00' + ((g * 17 % 200000) * INTERVAL '1 minute'),
    TIMESTAMPTZ '2020-01-01 00:00:00+00' + ((g * 17 % 200000) * INTERVAL '1 minute'),
    0
FROM generate_series(1, 200000) AS g;
ANALYZE payments;
SQL

TARGET="11111111-1111-1111-1111-111111111111"
PAGE_SQL="SELECT pje1_0.id, pje1_0.amount, pje1_0.created_at, pje1_0.currency, pje1_0.description, pje1_0.status, pje1_0.updated_at, pje1_0.user_id, pje1_0.version FROM payments pje1_0 WHERE pje1_0.user_id = '${TARGET}' ORDER BY pje1_0.created_at DESC, pje1_0.id DESC OFFSET 40 ROWS FETCH FIRST 20 ROWS ONLY"
DEEP_SQL="SELECT pje1_0.id, pje1_0.amount, pje1_0.created_at, pje1_0.currency, pje1_0.description, pje1_0.status, pje1_0.updated_at, pje1_0.user_id, pje1_0.version FROM payments pje1_0 WHERE pje1_0.user_id = '${TARGET}' ORDER BY pje1_0.created_at DESC, pje1_0.id DESC OFFSET 2000 ROWS FETCH FIRST 20 ROWS ONLY"
ASC_SQL="SELECT pje1_0.id, pje1_0.amount, pje1_0.created_at, pje1_0.currency, pje1_0.description, pje1_0.status, pje1_0.updated_at, pje1_0.user_id, pje1_0.version FROM payments pje1_0 WHERE pje1_0.user_id = '${TARGET}' ORDER BY pje1_0.created_at ASC, pje1_0.id ASC OFFSET 40 ROWS FETCH FIRST 20 ROWS ONLY"
COUNT_SQL="SELECT count(pje1_0.id) FROM payments pje1_0 WHERE pje1_0.user_id = '${TARGET}'"

{
  echo "PostgreSQL: $(docker exec "$NAME" psql -U postgres -d payments -tAc 'SELECT version();')"
  echo "Host: $(uname -sr)"
  echo "Generated by perf/explain.sh. 200000 rows; g % 80 = 0 is user ${TARGET} (2500 rows); created_at = 2020-01-01 + ((g * 17 % 200000) minutes)."
  echo "Indexes: payments_pkey, idx_payments_user_status, idx_payments_created_at. ANALYZE payments ran after the load."
  echo "Statements match Hibernate 6 (alias pje1_0) for ListPaymentsQueryHandler."
  echo
  echo "-- page query OFFSET 40"
  echo "$PAGE_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${PAGE_SQL};"
  echo "-- page query OFFSET 2000"
  echo "$DEEP_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${DEEP_SQL};"
  echo "-- count"
  echo "$COUNT_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${COUNT_SQL};"
} > "$ROOT/perf/explain-before.txt"

docker exec -i "$NAME" psql -U postgres -d payments -v ON_ERROR_STOP=1 <<'SQL'
CREATE INDEX CONCURRENTLY idx_payments_user_created_at_id
    ON payments (user_id, created_at DESC, id DESC);
DROP INDEX CONCURRENTLY idx_payments_created_at;
DROP INDEX CONCURRENTLY idx_payments_user_status;
ANALYZE payments;
SQL

{
  echo "PostgreSQL: $(docker exec "$NAME" psql -U postgres -d payments -tAc 'SELECT version();')"
  echo "Host: $(uname -sr)"
  echo "Same table after CREATE INDEX CONCURRENTLY idx_payments_user_created_at_id, DROP INDEX CONCURRENTLY of idx_payments_created_at and idx_payments_user_status, and ANALYZE."
  echo
  echo "-- page query OFFSET 40 DESC"
  echo "$PAGE_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${PAGE_SQL};"
  echo "-- page query OFFSET 2000 DESC"
  echo "$DEEP_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${DEEP_SQL};"
  echo "-- page query OFFSET 40 ASC"
  echo "$ASC_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${ASC_SQL};"
  echo "-- count"
  echo "$COUNT_SQL"
  docker exec "$NAME" psql -U postgres -d payments -c "EXPLAIN (ANALYZE, BUFFERS) ${COUNT_SQL};"
} > "$ROOT/perf/explain-after.txt"

docker rm -f "$NAME" >/dev/null
echo "wrote $ROOT/perf/explain-before.txt and $ROOT/perf/explain-after.txt"
